#!/usr/bin/env node
// Copies workflows/*.json into stack-map.html so the app's Automations panel can hand them to n8n.
// Usage: node scripts/embed-workflows.mjs          (rewrite the block)
//        node scripts/embed-workflows.mjs --check  (fail if the app is out of date)
import { readFileSync, writeFileSync } from 'node:fs';
const FILES = { scan: 'stack-map-scan-repo', mcp: 'stack-map-mcp-server', push: 'stack-map-push-guard', audit: 'stack-map-weekly-audit', errors: 'stack-map-error-alert' };
const data = Object.fromEntries(Object.entries(FILES).map(([k, f]) => [k, JSON.parse(readFileSync(`workflows/${f}.json`, 'utf8'))]));
const block = `/* WORKFLOWS:BEGIN (generated by scripts/embed-workflows.mjs, do not edit) */\nconst WORKFLOWS=${JSON.stringify(data).replace(/<\//g, '<\\/')};\n/* WORKFLOWS:END */`;
const html = readFileSync('stack-map.html', 'utf8');
const re = /\/\* WORKFLOWS:BEGIN[\s\S]*?WORKFLOWS:END \*\//;
if (!re.test(html)) { console.error('No WORKFLOWS block in stack-map.html'); process.exit(1); }
const next = html.replace(re, () => block);
if (process.argv.includes('--check')) {
  if (next !== html) { console.error('stack-map.html has old copies of the workflows. Run: node scripts/embed-workflows.mjs'); process.exit(1); }
  console.log('Embedded workflows are up to date.');
} else { writeFileSync('stack-map.html', next); console.log('Embedded', Object.keys(data).length, 'workflows into stack-map.html'); }
